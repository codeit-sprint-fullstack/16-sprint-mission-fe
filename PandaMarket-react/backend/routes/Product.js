// ======================================================================
// 4. 상품 API 파일 만들기
// ======================================================================
//
// backend/routes/products.js
//

import express from "express";
import Product from "../models/Product.js";

const router = express.Router();

// ======================================================================
// 4-1. POST /api/products
// 상품 등록
// ======================================================================
//
// 프론트에서:
//
// POST /api/products
//
// {
//   "name": "맥북",
//   "description": "깨끗하게 사용했습니다.",
//   "price": 1000000,
//   "tags": ["전자제품", "노트북"]
// }
//
// 를 보내면 MongoDB에 저장.
//
// ------------------------------------------------------

router.post("/", async (req, res) => {
  try {
    // ------------------------------------------------
    // 1. 프론트가 보낸 body 꺼내기
    // ------------------------------------------------

    const { name, description, price, tags } = req.body;

    // ------------------------------------------------
    // 2. 필수값 확인
    // ------------------------------------------------

    if (!name || !description || price === undefined) {
      return res.status(400).json({
        message: "name, description, price는 필수입니다.",
      });
    }

    // ------------------------------------------------
    // 3. 가장 큰 id 찾기
    // ------------------------------------------------
    //
    // MongoDB에:
    //
    // id: 1
    // id: 2
    // id: 3
    //
    // 이 있다면 가장 큰 3을 찾음.

    const lastProduct = await Product.findOne().sort({ id: -1 });

    // ------------------------------------------------
    // 4. 다음 id 만들기
    // ------------------------------------------------
    //
    // 상품이 하나도 없으면
    // id = 1
    //
    // 마지막 id가 3이면
    // id = 4

    const nextId = lastProduct ? lastProduct.id + 1 : 1;

    // ------------------------------------------------
    // 5. 새 상품 만들기
    // ------------------------------------------------

    const newProduct = await Product.create({
      id: nextId,
      name,
      description,
      price,
      tags: tags ?? [],
    });

    // ------------------------------------------------
    // 6. 저장된 상품 응답
    // ------------------------------------------------
    //
    // 새로 만들었기 때문에 201

    return res.status(201).json(newProduct);
  } catch (error) {
    console.error(error);

    return res.status(500).json({
      message: "상품 등록 중 오류가 발생했습니다.",
    });
  }
});

// ======================================================================
// 4-2. GET /api/products
// 상품 목록 가져오기
// ======================================================================
//
// 기본:
//
// GET /api/products
//
//          ↓
//
// MongoDB 상품 목록
//
//
// 그리고 미션에서 나중에 필요한:
//
// 페이지네이션
// 검색
// 최신순
//
// 도 같이 넣어두기.
//
// ------------------------------------------------------

router.get("/", async (req, res) => {
  try {
    // ------------------------------------------------
    // 주소에서 query string 꺼내기
    // ------------------------------------------------
    //
    // 예:
    //
    // /api/products?page=1&pageSize=10&keyword=맥북
    //
    // page     → 1
    // pageSize → 10
    // keyword  → 맥북

    const { page = 1, pageSize = 10, keyword = "" } = req.query;

    // ------------------------------------------------
    // query string은 문자열로 들어오기 때문에 숫자로 변경
    // ------------------------------------------------

    const pageNumber = Number(page);

    const size = Number(pageSize);

    // ------------------------------------------------
    // 몇 개를 건너뛸지 계산
    // ------------------------------------------------
    //
    // page = 1
    //
    // (1 - 1) * 10
    // = 0
    //
    // 처음부터 가져오기
    //
    //
    // page = 2
    //
    // (2 - 1) * 10
    // = 10
    //
    // 앞의 10개를 건너뛰기

    const skip = (pageNumber - 1) * size;

    // ------------------------------------------------
    // 검색 조건 만들기
    // ------------------------------------------------

    const filter = keyword
      ? {
          $or: [
            {
              name: {
                $regex: keyword,
                $options: "i",
              },
            },

            {
              description: {
                $regex: keyword,
                $options: "i",
              },
            },
          ],
        }
      : {};

    // ------------------------------------------------
    // 상품 목록 가져오기
    // ------------------------------------------------
    //
    // sort({ createdAt: -1 })
    //
    // -1 = 최신 → 오래된 순
    //
    // 즉 최신순

    const products = await Product.find(filter)
      .sort({ createdAt: -1 })
      .skip(skip)
      .limit(size);

    // ------------------------------------------------
    // 검색 조건에 맞는 전체 상품 개수
    // ------------------------------------------------

    const totalCount = await Product.countDocuments(filter);

    // ------------------------------------------------
    // 프론트로 응답
    // ------------------------------------------------

    return res.status(200).json({
      list: products,
      totalCount,
    });
  } catch (error) {
    console.error(error);

    return res.status(500).json({
      message: "상품 목록을 불러오는 중 오류가 발생했습니다.",
    });
  }
});

export default router;


